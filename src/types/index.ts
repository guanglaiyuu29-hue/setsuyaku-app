// ============================================================
// このファイルは「データの形（設計図）」を定義する場所です。
// 通常、ここは編集しません。
// 店舗や価格に「新しい項目」を増やしたくなったときだけ触ります。
// （例: 店舗に「定休日」を足したい → Store に `holiday: string` を追加）
// ============================================================

/** 店舗の情報 */
export interface Store {
  /** 店舗ID（英数字。他のファイルから店舗を指し示すための合言葉。重複禁止） */
  id: string
  /** 店舗名（画面に表示される名前） */
  name: string
  /** 家からの徒歩での所要時間（分） */
  walkMinutes: number
  /** 家からの自転車での所要時間（分） */
  bikeMinutes: number
  /** 補足メモ（例: "レジ袋は有料"）。無ければ空文字 "" でOK */
  note: string
}

/**
 * 価格データの出所。
 * - "official" : 運営（このアプリの管理者）が実際に店で調べた価格
 * - "receipt"  : ユーザーがレシートを投稿して登録された価格
 * - "sample"   : 動作確認用の仮の価格（実測ではない）。画面に「サンプルデータ」と表示する
 */
export type PriceSource = 'official' | 'receipt' | 'sample'

/**
 * 家から店までの移動手段。
 * - "walk" : 徒歩
 * - "bike" : 自転車
 * 画面の「移動手段を選択」トグルで切り替え、各カードの所要時間表示に反映する。
 */
export type TransportMode = 'walk' | 'bike'

/** 1つの食材の、1店舗での価格 */
export interface Price {
  /** 価格レコードのID（1件ごとに重複しない文字列。将来はDBが自動採番する） */
  id: string
  /** 食材名（例: "卵"）。同じ食材は表記を必ずそろえること */
  itemName: string
  /** どの店舗の価格か。Store の id と同じ文字列を書く */
  storeId: string
  /** 税込価格（円。数字のみ、カンマや "円" は書かない） */
  price: number
  /** 価格の単位・内容量（例: "10個入り1パック"、"100gあたり"） */
  unit: string
  /** その価格を確認した日（"YYYY-MM-DD" の形式。例: "2026-08-30"） */
  checkedAt: string
  /** データの出所（上の PriceSource を参照） */
  source: PriceSource
}
